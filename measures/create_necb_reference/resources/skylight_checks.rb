require 'json'
require_relative 'part8_reference'

# Keep this adapter outside the pinned standards tree. The upstream generator
# does not propagate every skylight failure back to model_apply_standard.
module NECBSkylightChecks
  def self.roofs(model)
    model.getSurfaces.select { |s| s.surfaceType == 'RoofCeiling' && s.outsideBoundaryCondition == 'Outdoors' }
  end

  def self.summary(surfaces)
    gross = surfaces.sum { |roof| roof.grossArea * roof.space.get.multiplier }
    skylights = surfaces.flat_map(&:subSurfaces).select { |s| s.subSurfaceType == 'Skylight' }
    area = skylights.sum { |s| s.grossArea * s.multiplier * s.surface.get.space.get.multiplier }
    {'gross_roof_area_m2' => gross, 'skylight_area_m2' => area,
     'skylight_count' => skylights.size, 'srr' => gross.positive? ? area / gross : 0.0}
  end

  def self.audit(model, source, standard, complete:)
    target = standard.get_standards_constant('skylight_to_roof_ratio_max_value')
    exposed = standard.find_exposed_conditioned_roof_surfaces(model)
    eligible = exposed.fetch('exp_nonplenum_roofs')
    all_roofs = roofs(model)
    validator = Object.new.extend(NECBPart8Reference)
    all_roofs.each { |roof| validator.validate_opening_geometry(roof) }
    if complete && exposed.fetch('exp_nonplenum_roof_area_m2') >= 0.1
      eligible.each do |roof|
        # This is the pinned prototype convention, not a claim that Part 8
        # requires a thermal opening in every roof. Refuse silent omissions.
        actual = summary([roof])
        expected = roof.grossArea * roof.space.get.multiplier * target
        unless (actual['skylight_area_m2'] - expected).abs <= [0.0001, expected * 1e-5].max
          raise "NRC skylight generation did not achieve #{target * 100}% on '#{roof.nameString}'. The pinned generator supports flat, exposed, conditioned non-plenum roofs; sloped roofs and skylight wells require project-specific modelling."
        end
        roof.subSurfaces.select { |s| s.subSurfaceType == 'Skylight' }.each do |sky|
          raise "Generated skylight '#{sky.nameString}' has no construction." if sky.construction.empty?
        end
      end
    end
    eligible_handles = eligible.map { |roof| roof.handle.to_s }
    plenum_handles = exposed.fetch('exp_plenum_roofs').map { |roof| roof.handle.to_s }
    {
      'mode' => complete ? 'NRCPrototypeSkylights' : 'CapExistingSkylights',
      'library_srr_limit' => target,
      'all_exterior_roofs_before' => summary(roofs(source)),
      'all_exterior_roofs_after' => summary(all_roofs),
      'exposed_conditioned_nonplenum_roofs_after' => summary(eligible),
      'roofs' => all_roofs.sort_by(&:nameString).map do |roof|
        eligible_roof = eligible_handles.include?(roof.handle.to_s)
        reason = if eligible_roof
                   complete ? 'Generated by the NRC prototype convention; area and geometry verified' : 'Existing skylights retained or reduced; no new thermal openings assumed'
                 elsif plenum_handles.include?(roof.handle.to_s)
                   'Plenum roof: default NRC generator does not create skylight wells'
                 else
                   'Unconditioned roof/attic: default NRC generator does not create skylight wells'
                 end
        {'surface' => roof.nameString, 'space' => roof.space.get.nameString, 'eligible_for_default_generator' => eligible_roof,
         'treatment' => reason}.merge(summary([roof]))
      end,
      'daylighting_scope' => 'NECB2020 8.4.4.5.(7) specifies an idealized skylight for daylighted-area calculations. It is not an unconditional instruction to insert thermal skylights through every roof. The pinned NRC daylight-control implementation is not a verified implementation of all Part 8 lighting calculations; review 8.4.4.5.(5)-(12).',
      'denominator_scope' => 'Reported ratios distinguish all exterior roofs from the roofs eligible for the NRC generator. These are diagnostics, not a substitute for the gross insulated roof area defined in NECB 3.1.1.6.'
    }
  end
end
