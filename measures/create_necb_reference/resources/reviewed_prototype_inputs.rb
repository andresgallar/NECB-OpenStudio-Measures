require 'digest'
require 'json'

# Recover missing inputs only from an unambiguous whole-model match to a pinned
# reviewed public shell. Match actual vertices, not Space names or floor area.
module NECBReviewedPrototypeInputs
  DEFAULT_PROPERTY = 'necb_default_building_use'.freeze

  def self.signature(space)
    faces = space.surfaces.map do |surface|
      points = surface.vertices.map do |vertex|
        point = space.transformation * vertex
        [point.x, point.y, point.z].map { |value| value.round(4) }
      end.sort
      [surface.surfaceType, points]
    end.sort
    Digest::SHA256.hexdigest(JSON.generate([space.multiplier, space.partofTotalFloorArea, faces]))
  end

  def self.previous_audit(model)
    value = model.getBuilding.additionalProperties.getFeatureAsString('necb_input_preparation')
    value.empty? ? [] : JSON.parse(value.get)
  rescue JSON::ParserError
    []
  end

  def self.owned_default?(space, audit)
    return false if space.spaceType.empty?
    type = space.spaceType.get
    pair = NECBSpaceTypeMapping.pair(type)
    return false unless pair[1] == 'WholeBuilding'
    marker = type.additionalProperties.getFeatureAsString(DEFAULT_PROPERTY)
    return true if !marker.empty? && marker.get == pair[0]
    # Upgrade only the earlier measure's documented autogenerated defaults.
    type.nameString == "NECB default #{pair[0]}" && audit.any? { |message| message.start_with?("Assigned #{pair[0]} / WholeBuilding to ") && message.include?('spaces without a Space Type') }
  end

  def self.apply(model, catalog, use, resources, repair_defaults: false)
    previous = previous_audit(model)
    eligible = model.getSpaces.select { |space| space.spaceType.empty? || (repair_defaults && owned_default?(space, previous)) }
    return [] if eligible.empty? || use.to_s.empty? || use == 'UseExisting'
    presets = JSON.parse(File.read(File.join(resources, 'mapping_presets.json')))
    signatures = model.getSpaces.to_h { |space| [space.handle.to_s, signature(space)] }
    wanted = signatures.values.sort
    matches = presets.filter_map do |_key, preset|
      family = File.basename(preset.fetch('source'), '.osm')
      next unless family == use || preset.fetch('mappings').any? { |row| row['source_building_type'] == use }
      path = File.expand_path(preset.fetch('source'), resources)
      next unless path.start_with?(File.expand_path('openstudio-standards/', resources) + '/') && File.file?(path)
      shell = OpenStudio::OSVersion::VersionTranslator.new.loadModel(OpenStudio::Path.new(path)).get
      next unless shell.getSpaces.size == model.getSpaces.size
      groups = shell.getSpaces.group_by { |space| signature(space) }
      next unless groups.values.all? { |spaces| spaces.size == 1 } && groups.keys.sort == wanted
      next unless eligible.all? do |space|
        target = groups.fetch(signatures.fetch(space.handle.to_s)).first
        !target.spaceType.empty? && catalog.fetch('NECB2011').include?(NECBSpaceTypeMapping.pair(target.spaceType.get))
      end
      [family, shell, groups]
    end
    return [] unless matches.size == 1
    family, shell, groups = matches.first
    types = {}
    recovered = []
    old_stories = []
    eligible.each do |space|
      target = groups.fetch(signatures.fetch(space.handle.to_s)).first
      pair = NECBSpaceTypeMapping.pair(target.spaceType.get)
      type = types[pair] ||= begin
        item = OpenStudio::Model::SpaceType.new(model)
        item.setName("NECB reviewed #{family} #{pair[1]}")
        item.setStandardsBuildingType(pair[0])
        item.setStandardsSpaceType(pair[1])
        item
      end
      space.setSpaceType(type)
      recovered << {'space' => space.nameString, 'necb_vintage' => 'NECB2011', 'necb_building_type' => pair[0], 'necb_space_type' => pair[1]}
      # Restore missing or measure-inferred stories; keep supplied stories.
      inferred_story = !space.buildingStory.empty? && space.buildingStory.get.nameString.start_with?('NECB Story at ') && previous.any? { |message| message.start_with?("Assigned '#{space.nameString}' to a story using floor elevation") }
      if (space.buildingStory.empty? || inferred_story) && !target.buildingStory.empty?
        old_stories << space.buildingStory.get if inferred_story
        target_story = target.buildingStory.get
        elevation = target_story.nominalZCoordinate.get
        story = model.getBuildingStorys.find { |item| !item.nominalZCoordinate.empty? && (item.nominalZCoordinate.get - elevation).abs < 0.001 }
        unless story
          story = OpenStudio::Model::BuildingStory.new(model)
          story.setName("NECB reviewed #{family} #{target_story.nameString}")
          story.setNominalZCoordinate(elevation)
          story.setNominalFloortoFloorHeight(target_story.nominalFloortoFloorHeight.get) unless target_story.nominalFloortoFloorHeight.empty?
        end
        space.setBuildingStory(story)
      end
    end
    old_stories.uniq(&:handle).each { |story| story.remove if story.spaces.empty? }
    building = model.getBuilding
    building.setStandardsBuildingType(family) if building.standardsBuildingType.empty?
    inferred_counts = previous.any? { |message| message.start_with?('Missing story counts inferred') }
    if (building.standardsNumberOfStories.empty? || inferred_counts) && !shell.getBuilding.standardsNumberOfStories.empty?
      building.setStandardsNumberOfStories(shell.getBuilding.standardsNumberOfStories.get)
    end
    if (building.standardsNumberOfAboveGroundStories.empty? || inferred_counts) && !shell.getBuilding.standardsNumberOfAboveGroundStories.empty?
      building.setStandardsNumberOfAboveGroundStories(shell.getBuilding.standardsNumberOfAboveGroundStories.get)
    end
    building.additionalProperties.setFeature('necb_reviewed_prototype_inputs', JSON.generate('prototype' => family, 'match' => 'all Space surface vertices, floor-area participation and multipliers; coordinates rounded to 0.1 mm', 'assignments' => recovered))
    ["Recovered reviewed #{family} uses for #{eligible.size} spaces with missing/measure-default Space Types from a complete public-shell geometry match; occupied spaces and plenums are distinct. No geometry or systems copied."]
  end
end
